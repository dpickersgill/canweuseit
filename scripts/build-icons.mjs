// Copies the few Lucide icons the app uses into public/icons.js (no runtime dependency, one small file).
// Lucide is ISC licensed: https://lucide.dev/license
import { writeFileSync } from 'node:fs';
const names = ['calendar', 'calendar-days', 'list', 'inbox', 'circle-plus', 'users', 'cloud-rain', 'trophy', 'receipt', 'chart-column', 'settings', 'menu',
  'chevron-left', 'chevron-right', 'chevron-down', 'ellipsis', 'check', 'x', 'clock', 'triangle-alert', 'circle-check', 'circle-x', 'lock', 'lightbulb',
  'map-pin', 'search', 'log-out', 'user', 'sun', 'moon', 'monitor', 'move', 'calendar-x', 'undo-2', 'file-text', 'pencil', 'mail', 'external-link',
  'download', 'filter', 'shield-check', 'credit-card', 'layers', 'map', 'upload', 'arrow-right', 'arrow-left', 'sparkles', 'bell', 'ban', 'land-plot', 'diamond', 'dribbble', 'route', 'waves', 'snowflake', 'tent', 'trees', 'square-parking', 'dumbbell', 'school', 'door-open', 'presentation', 'theater', 'utensils', 'chef-hat', 'library', 'users-round', 'house'];
const out = {};
for (const n of names) {
  const mod = await import(`../node_modules/lucide/dist/esm/icons/${n}.js`);
  out[n] = mod.default[2];
}
writeFileSync(new URL('../public/icons.js', import.meta.url), `// Generated by scripts/build-icons.mjs from Lucide ${'v0.460.0'} (ISC licence, https://lucide.dev/license). Do not edit.
const ICONS = ${JSON.stringify(out)};
const NS = 'http://www.w3.org/2000/svg';
// An inline SVG icon. Decorative by default (hidden from screen readers); pass a label when the icon is the only content.
export function icon(name, { size = 20, label } = {}) {
  const svg = document.createElementNS(NS, 'svg');
  for (const [k, v] of Object.entries({ width: size, height: size, viewBox: '0 0 24 24', fill: 'none', stroke: 'currentColor', 'stroke-width': 1.75, 'stroke-linecap': 'round', 'stroke-linejoin': 'round', class: 'ic' })) svg.setAttribute(k, v);
  if (label) { svg.setAttribute('role', 'img'); svg.setAttribute('aria-label', label); } else svg.setAttribute('aria-hidden', 'true');
  for (const [tag, attrs] of ICONS[name] || []) { const n = document.createElementNS(NS, tag); for (const [k, v] of Object.entries(attrs)) n.setAttribute(k, v); svg.append(n); }
  return svg;
}
`);
console.log('icons', Object.keys(out).length);
